"""Export the provenance-stamped clause-kind dataset (Line I training data).

Two adapters, one record shape {id, text, kind, source, provenance}:

1. optmem_tree (default) — the memory-note corpus (~/.optmem/memory/TREE),
   segmented into clauses by the CANONICAL deterministic teacher,
   ecsly_context's segmentText (TRAIN-GATES.md oracle law 4: imported,
   never re-implemented). kind ∈ {open, done, action, fact}.

2. codemap_meaning_units (--codemap-store + --repo-root) — code-structure
   units (kind ∈ block/function/type/name) with the best provenance in the
   ecosystem (repo_id + path + char span); text is recovered from the repo
   checkout at the recorded span. Optional secondary dataset for typed
   code-shaped jobs.

WHY THE SHIM IS GENERATED (paid-for gotcha): segment.dart uses final
parameters, legal only at languageVersion <= 3.12 — the ecsai_harness
workspace registers it at 3.12, but a script importing it from OUTSIDE any
package config gets the current default version and the CFE rejects it
("Can't have modifier 'final' here"). Dart resolves packages from the
entry script's directory upward, not the cwd. So the labeler shim is
GENERATED under <segmenter-repo>/.dart_tool/nursery_shim/ (scratch, never
committed), where package-config discovery registers the teacher at 3.12,
and imports it by relative path. The teacher file itself is never copied
or modified.

Provenance stamps the teacher: sha256(segment.dart) rides on every record
and the dataset manifest, so a teacher change is detectable in trained
artifacts forever.

Usage:
  ~/.venvs/mlx-ref/bin/python export_clause_dataset.py \
      [--tree-dir ~/.optmem/memory/TREE] [--out bench/nursery/data/clause_dataset.jsonl]
  ... --codemap-store ~/.codemap/store/meaning_units \
      --repo-root /Users/antonio/xs/codemap --out-codemap bench/nursery/data/codemap_units.jsonl

Requires: dart at --dart (default /opt/homebrew/bin/dart — the fvm 3.13.4
front-end crashes; the justfile pins the same override).
"""

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile

SHIM_TEMPLATE = """// GENERATED by tool/nursery/export_clause_dataset.py — do not edit.
// Lives here (inside the teacher's workspace) so package-config discovery
// registers segment.dart at languageVersion 3.12 (final-parameters gotcha).
import '{segmenter_rel}';
import 'dart:convert';
import 'dart:io';

void main() {{
  stdin.transform(utf8.decoder).transform(const LineSplitter()).listen((line) {{
    final trimmed = line.trim();
    if (trimmed.isEmpty) return;
    final dynamic row;
    try {{
      row = jsonDecode(trimmed);
    }} on FormatException {{
      stderr.writeln('unparsable row: $trimmed');
      exitCode = 2;
      return;
    }}
    final text = row['text'] as String?;
    if (text == null) {{
      stderr.writeln('row without text: $trimmed');
      exitCode = 2;
      return;
    }}
    final seg = segmentText(text);
    print(jsonEncode({{
      'date_token': seg.dateToken,
      'topic': seg.topic,
      'clauses': [for (final c in seg.clauses)
        {{'index': c.index, 'start': c.start, 'end': c.end,
          'text': c.text, 'kind': c.kind.name}}],
    }}));
  }});
}}
"""


def sha256_file(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def build_shim(segmenter_repo, segmenter_path, dart):
    """Generates the labeler shim inside the teacher's workspace and
    returns its path."""
    shim_dir = os.path.join(segmenter_repo, ".dart_tool", "nursery_shim")
    os.makedirs(shim_dir, exist_ok=True)
    rel = os.path.relpath(segmenter_path, shim_dir)
    shim_path = os.path.join(shim_dir, "segment_labels.dart")
    with open(shim_path, "w") as fh:
        fh.write(SHIM_TEMPLATE.format(segmenter_rel=rel))
    # Smoke: the teacher must parse and answer before we trust labels.
    probe_in = tempfile.NamedTemporaryFile("w", suffix=".ndjson", delete=False)
    probe_in.write(json.dumps({"text": "Landed the fixture. TODO: label it."}) + "\n")
    probe_in.close()
    result = subprocess.run(
        [dart, "run", shim_path], stdin=open(probe_in.name),
        capture_output=True, text=True, timeout=300)
    os.unlink(probe_in.name)
    rows = [ln for ln in result.stdout.splitlines() if ln.startswith("{")]
    if result.returncode != 0 or not rows:
        raise SystemExit(
            "labeler shim failed its smoke probe — fix the teacher path or "
            f"the dart toolchain.\nstdout tail: {result.stdout[-400:]}\n"
            f"stderr tail: {result.stderr[-800:]}")
    return shim_path


def label(texts, shim_path, dart):
    """Runs the shim once over all texts; returns parsed segmentation rows."""
    with tempfile.NamedTemporaryFile("w", suffix=".ndjson", delete=False) as fh:
        for text in texts:
            fh.write(json.dumps({"text": text}) + "\n")
        in_path = fh.name
    with open(in_path) as stdin_fh:
        result = subprocess.run(
            [dart, "run", shim_path], stdin=stdin_fh,
            capture_output=True, text=True, timeout=1800)
    os.unlink(in_path)
    if result.returncode != 0:
        raise SystemExit(f"labeler failed: {result.stderr[-800:]}")
    rows = []
    for line in result.stdout.splitlines():
        line = line.strip()
        if line.startswith("{"):
            rows.append(json.loads(line))
    if len(rows) != len(texts):
        raise SystemExit(
            f"labeler returned {len(rows)} rows for {len(texts)} texts — "
            "refusing to write a misaligned dataset")
    return rows


def export_optmem_tree(tree_dir, shim_path, dart, segmenter_sha):
    records = []
    for name in sorted(os.listdir(tree_dir)):
        path = os.path.join(tree_dir, name)
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8") as fh:
            lines = fh.read().splitlines()
        notes = [(n, ln) for n, ln in enumerate(lines, 1) if ln.strip()]
        if not notes:
            continue
        segs = label([ln for _, ln in notes], shim_path, dart)
        for (n, raw), seg in zip(notes, segs):
            for clause in seg["clauses"]:
                records.append({
                    "id": f"tree-{name}-L{n}-C{clause['index']}",
                    "text": clause["text"],
                    "kind": clause["kind"],
                    "source": "optmem_tree",
                    "provenance": {
                        "file": f"TREE/{name}",
                        "line": n,
                        "date_token": seg.get("date_token", ""),
                        "topic": seg.get("topic"),
                        "clause_span": [clause["start"], clause["end"]],
                        "labeler": "ecsly_context/segmentText",
                        "segmenter_sha256": segmenter_sha,
                    },
                })
    return records


def export_codemap_units(store_dir, repo_root, cap):
    """Text recovered at the recorded span; no labeling pass needed (the
    kind IS the unit kind from the store)."""
    records, skipped = [], 0
    files = sorted(f for f in os.listdir(store_dir) if f.endswith(".json"))
    for name in files:
        if cap and len(records) >= cap:
            break
        with open(os.path.join(store_dir, name)) as fh:
            bundle_doc = json.load(fh)
        bundle = bundle_doc.get("bundle", {})
        rel = bundle_doc.get("rel") or bundle.get("path")
        if not rel:
            continue
        source_path = os.path.join(repo_root, rel)
        try:
            with open(source_path, encoding="utf-8") as fh:
                src_lines = fh.read().splitlines()
        except OSError:
            skipped += 1
            continue
        for group in ("blocks", "functions", "types", "names"):
            for unit in bundle.get(group) or []:
                if cap and len(records) >= cap:
                    break
                span = unit.get("span")
                if not span or "lineno" not in span:
                    continue
                lo = max(int(span["lineno"]) - 1, 0)
                hi = min(int(span["end_lineno"]), len(src_lines))
                if lo >= hi:
                    skipped += 1
                    continue
                text = "\n".join(src_lines[lo:hi]).strip()
                if not text:
                    skipped += 1
                    continue
                records.append({
                    "id": unit.get("id") or f"{group}:{rel}",
                    "text": text,
                    "kind": unit.get("kind") or group,
                    "source": "codemap_meaning_units",
                    "provenance": {
                        "repo_id": bundle_doc.get("repo_id"),
                        "path": rel,
                        "span": span,
                        "language": unit.get("language"),
                        "store_file": name,
                        "content_sha256": bundle_doc.get("content_sha256"),
                    },
                })
    return records, skipped


def write_dataset(records, out_path, extra_manifest=None):
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        for r in records:
            fh.write(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n")
    kinds = {}
    for r in records:
        kinds[r["kind"]] = kinds.get(r["kind"], 0) + 1
    manifest = {
        "contract": "nursery.clause-dataset.v1",
        "records": len(records),
        "kinds": dict(sorted(kinds.items())),
        "dataset_sha256": sha256_file(out_path),
    }
    manifest.update(extra_manifest or {})
    with open(out_path + ".manifest.json", "w") as fh:
        json.dump(manifest, fh, indent=2, sort_keys=True)
    print(json.dumps(manifest, indent=2))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--tree-dir", default=os.path.expanduser("~/.optmem/memory/TREE"))
    ap.add_argument("--out", default="bench/nursery/data/clause_dataset.jsonl")
    ap.add_argument("--segmenter-repo", default="/Users/antonio/xs/ecsai_harness")
    ap.add_argument("--segmenter",
                    default="/Users/antonio/xs/ecsai_harness/pkgs/ecsly_context/lib/src/segment.dart")
    ap.add_argument("--dart", default="/opt/homebrew/bin/dart",
                    help="the fvm 3.13.4 front-end crashes; this pin matches "
                         "the harness justfile's HARNESS_TEST_DART default")
    ap.add_argument("--codemap-store")
    ap.add_argument("--repo-root")
    ap.add_argument("--out-codemap")
    ap.add_argument("--cap", type=int, default=0, help="cap codemap records (0 = no cap)")
    args = ap.parse_args(argv)

    if not os.path.exists(args.segmenter):
        raise SystemExit(f"teacher missing: {args.segmenter}")
    if not os.path.exists(args.tree_dir):
        raise SystemExit(f"tree missing: {args.tree_dir} — run the memo store "
                         "or pass --tree-dir")
    segmenter_sha = sha256_file(args.segmenter)
    shim = build_shim(args.segmenter_repo, args.segmenter, args.dart)
    print(f"labeler shim: {shim} (teacher sha256 {segmenter_sha[:16]}…)")

    if not args.out and not args.out_codemap:
        ap.error("nothing to export: pass --out and/or --out-codemap")

    if args.out:
        records = export_optmem_tree(args.tree_dir, shim, args.dart,
                                     segmenter_sha)
        if not records:
            raise SystemExit("tree produced zero clauses — refusing to write "
                             "an empty dataset")
        print(f"== clause dataset ({args.out})")
        write_dataset(records, args.out, {
            "teacher": {"path": args.segmenter, "sha256": segmenter_sha},
            "tree_dir": args.tree_dir,
        })

    if args.out_codemap:
        if not (args.codemap_store and args.repo_root):
            ap.error("--out-codemap needs --codemap-store and --repo-root")
        print(f"== codemap unit dataset ({args.out_codemap})")
        records, skipped = export_codemap_units(
            args.codemap_store, args.repo_root, args.cap)
        print(f"skipped (unreadable/empty spans): {skipped}")
        write_dataset(records, args.out_codemap, {
            "codemap_store": args.codemap_store,
            "repo_root": args.repo_root,
        })
    return 0


if __name__ == "__main__":
    sys.exit(main())
