"""decomp_skeleton_dataset.py — the generated skeleton→fill corpus (Line SK).

WHY THIS EXISTS. The tracked decompression lane (`testdata/bench/
decompression_lane.json`) is a FROZEN 10-case oracle — enough for a scorecard
cell, too few for a paired significance test. Line SK (skeleton→fill,
MTP-GATES.md Part 7) needs the SAME oracle shape at n=90, generated by
FROZEN deterministic rules from provenance-stamped records, so the corpus is
re-derivable and auditable and the oracle law is continuous with the tracked
lane: max_output_bytes=280, min_entity_hits=2 of 5 entities, one line,
max_tokens=96 per case.

SOURCES (both are memory-record prose — the same distribution as the
hand-built lane cases, which are lane-history/memory-index lines):
  a) the optmem memo TREE (~/.optmem/memory/TREE/*), lines 300–1400 bytes;
  b) this project's zcode memory-index lines (~/.zcode/cli/memories/projects/
     dart_flutter_packages-*/memory/*.md), the long `- [...] — ...` rows.

FROZEN RULES (changing any of these after the Part-7 freeze makes the corpus
a NEW dataset requiring a NEW frozen Part):
  * record: one line, 300 ≤ utf8 bytes ≤ 900, printable-ASCII ratio ≥ 0.95,
    space ratio ≥ 0.10 (excludes nap-fold token-dense lines), ≥ 4 distinct
    entity candidates;
  * entity candidates (rule v2, pre-freeze audit revision): regex
    [A-Za-z][A-Za-z0-9_.-]{3,39} tokens minus the stoplist below, split into
    IDENTIFIER-LIKE (contains _, ., -, a digit, or internal/leading
    uppercase) and PLAIN words; identifier-like are ranked first, each class
    by (frequency desc, length desc, first position asc); top 5 taken. The
    audit that forced this rule: plain-word ranking promoted `nearly`,
    `always`, `messages` — carrying those tests nothing;
  * sampling: candidate records ranked by sha256(source_id), first 90 taken
    — deterministic, seed-free;
  * ids: `skel-<sha8>`; per-case provenance (source file + line) is kept in
    the manifest, never in the prompt.

The entity rule is mechanical, not semantic: it selects tokens a summary must
CARRY, exactly like the hand-built lane's entity lists. It does not claim the
top-5 tokens are "the meaning" — the oracle law (≥2 of 5 under the cap, one
line) is the frozen contract, same as the tracked lane's.

Usage:
  python tool/nursery/decomp_skeleton_dataset.py                # write dataset+manifest
  python tool/nursery/decomp_skeleton_dataset.py --audit 6      # print sample cases, write nothing
"""

import argparse
import hashlib
import json
import os
import re
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(os.path.dirname(HERE))
DATA = os.path.join(PKG, "bench", "nursery", "data")

TREE_DIR = os.path.expanduser("~/.optmem/memory/TREE")
MEMORY_GLOB = os.path.expanduser(
    "~/.zcode/cli/memories/projects/dart_flutter_packages-*/memory"
)

N_CASES = 90
MIN_BYTES = 300
MAX_BYTES = 1400
MIN_SPACE_RATIO = 0.10
MIN_PRINTABLE_RATIO = 0.95
N_ENTITIES = 5
MIN_ENTITY_CANDIDATES = 4
MAX_OUTPUT_BYTES = 280  # the tracked lane's law
MIN_ENTITY_HITS = 2      # the tracked lane's law
CASE_MAX_TOKENS = 96     # the tracked lane's law

TOKEN_RE = re.compile(r"[A-Za-z][A-Za-z0-9_.-]{3,39}")

# Pure function words only — NO domain words (a domain stoplist would delete
# real entities like `gate` or `adapter` from lane prose).
STOPLIST = {
    "the", "and", "for", "from", "with", "that", "this", "was", "were",
    "are", "has", "have", "had", "not", "but", "all", "its", "into",
    "only", "when", "then", "than", "will", "would", "can", "could",
    "should", "may", "might", "must", "one", "two", "per", "via", "any",
    "each", "other", "same", "such", "these", "those", "there", "here",
    "what", "which", "who", "whom", "whose", "why", "how", "been", "being",
    "also", "both", "either", "neither", "every", "under", "over", "after",
    "before", "between", "against", "because", "while", "until", "since",
    "them", "they", "their", "itself", "onto", "upon", "within", "without",
    "across", "through", "during", "above", "below", "more", "most", "less",
    "least", "much", "many", "several", "single", "double", "first", "second",
    "third", "last", "next", "prior", "still", "just", "now", "today",
    "yes", "no", "true", "false", "null", "none", "done_", "note", "notes",
    # audit additions (rule v2): generic adverbs and hyper-generic
    # communication nouns that carrying-them tests nothing
    "nearly", "always", "never", "often", "already", "really", "actually",
    "currently", "recently", "previously", "immediately", "exactly",
    "simply", "literally", "everything", "something", "nothing", "anything",
    "someone", "anyone", "everyone", "message", "messages", "line", "lines",
    "file", "files", "thing", "things", "lot", "bit", "bits", "kind",
    "kinds", "sort", "way", "ways", "part", "parts", "word", "words",
    "never_", "owner", "owners",
}


def sha8(s):
    return hashlib.sha256(s.encode()).hexdigest()[:8]


def _is_identifier_like(tok):
    if "_" in tok or "." in tok or "-" in tok:
        return True
    if any(ch.isdigit() for ch in tok):
        return True
    inner = tok[1:]
    return any(ch.isupper() for ch in inner) or tok.isupper()


def entity_candidates(record):
    counts = {}
    first_pos = {}
    for m in TOKEN_RE.finditer(record):
        tok = m.group(0)
        low = tok.lower()
        if low in STOPLIST or low.rstrip("._-") in STOPLIST:
            continue
        counts[tok] = counts.get(tok, 0) + 1
        if tok not in first_pos:
            first_pos[tok] = m.start()

    def rank(t):
        return (-counts[t], -len(t), first_pos[t], t)

    ident = sorted((t for t in counts if _is_identifier_like(t)), key=rank)
    plain = sorted((t for t in counts if not _is_identifier_like(t)), key=rank)
    return ident + plain


def record_ok(text):
    b = len(text.encode("utf-8"))
    if b < MIN_BYTES or b > MAX_BYTES:
        return False
    if text.count(" ") / len(text) < MIN_SPACE_RATIO:
        return False
    printable = sum(
        1 for ch in text if unicodedata.category(ch)[0] != "C" and ord(ch) < 0x2500
    )
    if printable / len(text) < MIN_PRINTABLE_RATIO:
        return False
    return len(entity_candidates(text)) >= MIN_ENTITY_CANDIDATES


def harvest():
    """All candidate records with frozen provenance ids."""
    out = []
    if os.path.isdir(TREE_DIR):
        for name in sorted(os.listdir(TREE_DIR)):
            path = os.path.join(TREE_DIR, name)
            if not os.path.isfile(path):
                continue
            with open(path, encoding="utf-8", errors="replace") as fh:
                for ln, line in enumerate(fh, 1):
                    line = line.strip()
                    if line and record_ok(line):
                        out.append(
                            {
                                "source_id": f"tree:{name}:L{ln}",
                                "source": "optmem_tree",
                                "record": line,
                            }
                        )
    else:
        print(f"WARN: tree missing: {TREE_DIR}", file=sys.stderr)
    import glob as _glob

    for path in sorted(_glob.glob(os.path.join(MEMORY_GLOB, "*.md"))):
        base = os.path.basename(path)
        with open(path, encoding="utf-8", errors="replace") as fh:
            for ln, line in enumerate(fh, 1):
                line = line.strip()
                if line and record_ok(line):
                    out.append(
                        {
                            "source_id": f"memo:{base}:L{ln}",
                            "source": "project_memory",
                            "record": line,
                        }
                    )
    return out


def build():
    pool = harvest()
    pool.sort(key=lambda r: hashlib.sha256(r["source_id"].encode()).hexdigest())
    cases = []
    manifest_rows = []
    for r in pool:
        if len(cases) >= N_CASES:
            break
        ents = entity_candidates(r["record"])[:N_ENTITIES]
        cid = f"skel-{sha8(r['source_id'])}"
        cases.append(
            {
                "id": cid,
                "record": r["record"],
                "entities": ents,
                "max_tokens": CASE_MAX_TOKENS,
            }
        )
        manifest_rows.append(
            {"id": cid, "source_id": r["source_id"], "source": r["source"],
             "bytes": len(r["record"].encode("utf-8"))}
        )
    dataset = {
        "lane": "decomp_skeleton",
        "description": (
            "Generated skeleton→fill corpus (Line SK). Oracle law continuous "
            "with testdata/bench/decompression_lane.json: one line, "
            f"<= {MAX_OUTPUT_BYTES} bytes, >= {MIN_ENTITY_HITS} of "
            f"{N_ENTITIES} frozen-rule entities. Deterministic generator "
            "(tool/nursery/decomp_skeleton_dataset.py); provenance in the "
            "manifest, never in the prompt."
        ),
        "max_output_bytes": MAX_OUTPUT_BYTES,
        "min_entity_hits": MIN_ENTITY_HITS,
        "cases": cases,
    }
    return dataset, manifest_rows, len(pool)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--audit", type=int, default=0)
    ap.add_argument("--out", default=os.path.join(DATA, "decomp_skeleton_dataset.json"))
    args = ap.parse_args()

    dataset, manifest_rows, pool_n = build()
    if args.audit:
        for c in dataset["cases"][: args.audit]:
            prov = next(m["source_id"] for m in manifest_rows if m["id"] == c["id"])
            print(f"--- {c['id']} ({prov}, {len(c['record'].encode())}B)")
            print("record:", c["record"][:200])
            print("entities:", c["entities"])
        print(f"pool={pool_n} cases={len(dataset['cases'])}")
        return 0

    if len(dataset["cases"]) < N_CASES:
        raise SystemExit(
            f"only {len(dataset['cases'])} candidate records — the frozen "
            f"rules need >= {N_CASES}; widen the sources in a NEW frozen "
            "revision, never silently shrink n"
        )
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as fh:
        json.dump(dataset, fh, indent=1)
    digest = hashlib.sha256(open(args.out, "rb").read()).hexdigest()
    manifest = {
        "dataset": os.path.relpath(args.out, PKG),
        "dataset_sha256": digest,
        "generator": "tool/nursery/decomp_skeleton_dataset.py",
        "generator_sha256": hashlib.sha256(
            open(os.path.join(HERE, "decomp_skeleton_dataset.py"), "rb").read()
        ).hexdigest(),
        "pool_candidates": pool_n,
        "n_cases": len(dataset["cases"]),
        "oracle_law": {
            "max_output_bytes": MAX_OUTPUT_BYTES,
            "min_entity_hits": MIN_ENTITY_HITS,
            "n_entities": N_ENTITIES,
            "one_line": True,
            "case_max_tokens": CASE_MAX_TOKENS,
        },
        "provenance": manifest_rows,
    }
    mpath = args.out.replace(".json", ".manifest.json")
    with open(mpath, "w") as fh:
        json.dump(manifest, fh, indent=1)
    print(f"wrote {args.out} ({len(dataset['cases'])} cases, pool={pool_n})")
    print(f"dataset sha256: {digest}")
    print(f"manifest: {mpath}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
