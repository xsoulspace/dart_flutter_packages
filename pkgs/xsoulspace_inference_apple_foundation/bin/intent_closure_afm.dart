/// Stage I3 — real-AFM intent closure: the bookmark-manager end-to-end loop.
///
/// The tiny 2–4k on-device model SHAPES the executor logic through meaning
/// moves (one `act_with_project` tool, closed enum) + `intent_define` +
/// `intent_call`. It never writes a code token: the host materializer
/// compiles the op chains into the suite's `program.dart` contract, and the
/// INTENT-graded oracle replays real intent calls (`dart run
/// intent_runner.dart`) — the same `intents` checker the scripted suite uses.
///
/// `Agent = G ∘ F` holds: only the model's tiny selections are
/// non-deterministic; materialization, verification, and projection are
/// pure host programs.
library;

import 'dart:io';

import 'package:xsoulspace_agentic_harness/xsoulspace_agentic_harness.dart';
import 'package:xsoulspace_agentic_harness/src/tooling/act_with_project.dart'
    show actWithProjectTool;
import 'package:xsoulspace_agentic_harness/src/tools/fs_tools.dart'
    show FsToolsRoot, runTool;
import 'package:xsoulspace_inference_apple_foundation/src/native_bridge/native_client.dart';

/// Sentinel oracle result for "the loop never ran".
final ProcessResult _notRun = ProcessResult(0, -1, '', 'not run');

/// The intent-graded oracle: same shape as the suite's `intents` checker
/// (checkers.dart). Deterministic — real Dart subprocess, real program.dart.
const _intentRunnerSource = r'''
// GENERATED by intent_closure_afm (Stage I3 oracle).
// Replays scripted intent calls against the materialized program
// (program.dart: initialState() + runIntent(name, state, args)) and exits 0
// iff every expectation holds.
import 'dart:convert';
import 'dart:io';
import 'program.dart' as program;

void main() {
  final spec = jsonDecode(File('intent_calls.json').readAsStringSync()) as Map;
  final calls = (spec['calls'] as List).cast<Map>();
  var state = program.initialState();
  var ok = true;
  final log = <String>[];
  for (final call in calls) {
    final name = call['intent'] as String;
    final args =
        ((call['args'] ?? const {}) as Map).cast<String, dynamic>();
    final expect =
        ((call['expect'] ?? const {}) as Map).cast<String, dynamic>();
    Map<String, dynamic> result;
    try {
      result = program.runIntent(name, state, args);
      state = (result['_state'] ?? state) as Map<String, dynamic>;
      result = (result['_result'] ?? result) as Map<String, dynamic>;
    } catch (e) {
      result = {'error': e.toString()};
    }
    final callOk = !result.containsKey('error') &&
        expect.entries.every((e) => result[e.key] == e.value);
    ok = ok && callOk;
    log.add(name + ' -> ' + result.toString());
  }
  stdout.writeln(ok
      ? 'intents: all ' + calls.length.toString() + ' calls verified'
      : 'intents failed: ' + log.join('; '));
  exit(ok ? 0 : 1);
}
''';

const _oracleCalls = '''
{"calls": [
  {"intent": "save_url", "args": {"url": "https://example.dev"}, "expect": {"saved": true}},
  {"intent": "save_url", "args": {"url": "https://second.dev"}},
  {"intent": "list_saved", "expect": {"value": 2}},
  {"intent": "save_url", "args": {"url": "not-a-url"}, "expect": {"saved": false}}
]}
''';

/// Meter: decisions (generate calls) + honest projection tokens
/// (Situation.tokensUsed). Move counts come from the world's durable tool
/// beats AFTER the run — internal tool rounds never surface on the final
/// response, so they must be read from thread history.
class _I3Meter implements GenerationHandler {
  _I3Meter(this.inner);
  final GenerationHandler inner;
  int decisions = 0;
  int projectionTokens = 0;

  @override
  Future<ActorGenerateResponse> generate(
    World world,
    ActorGenerateRequest request,
  ) async {
    final situation = world.getEntity(request.actorEntity).$1.get<Situation>();
    if (situation != null) projectionTokens += situation.tokensUsed;
    final response = await inner.generate(world, request);
    decisions++;
    return response;
  }
}

Future<void> main(List<String> args) async {
  final client = AppleFoundationNativeClient();
  await client.load();
  if (!await client.refreshAvailability()) {
    stderr.writeln('Apple Foundation Model unavailable.');
    exit(2);
  }

  final world = World()..addPlugin(AgentPlugin());
  final router = ModelRouter(
    inferenceClientsBuilders: {
      DefaultModelNames.appleFoundation: () => AppleFoundationNativeClient(),
    },
  );
  final modelId = ModelId('intent_closure');
  router.models[modelId] = Model(
    id: modelId,
    name: DefaultModelNames.appleFoundation,
  );
  world
    ..upsertResource(ModelRouterResource(router))
    ..upsertResource(ToolRegistryResource())
    // Meaning moves are structurally move-dense (I1/I2 finding): give the
    // chain generous headroom so a full bookmark build can't hit the cap.
    ..upsertResource(AgencyPolicy(maxConcurrent: 1, maxToolRounds: 48))
    ..flush();

  final meter = _I3Meter(DefaultGenerationHandler(router: router));
  world.getResource<GenerationHandlerResource>().registerDefault(meter);

  final jail = await Directory.systemTemp.createTemp('intent_closure_');
  final registry = ToolRegistry();
  registry.register(actWithProjectTool(
    world: world,
    materialize: () async {
      // Host program: meaning tree (op chains) -> real program.dart.
      final src = materializeMeaningProgram(world);
      File('${jail.path}/program.dart').writeAsStringSync(src);
      return {
        'path': 'program.dart',
        'materialized': true,
        'intents': [for (final i in listIntents(world)) i['name']],
        // Host-side chain validation: broken impl chains are caught NOW
        // (op ids included) instead of one oracle round later.
        'problems': validateMeaningProgram(world),
      };
    },
  ));
  registry.register(intentDefineTool(world));
  registry.register(intentCallTool(world));
  registry.register(runTool(FsToolsRoot(jail.path)));
  world.getResource<ToolRegistryResource>().register('default', registry);

  final scene = world.spawnComponents([Scene(), SceneFrame()]);
  final actor = world.spawnComponents([
    Actor(agentId: AgentId.create()),
    ActorModel(modelId: modelId),
    ActorSystemPrompt(
      text: 'You build a bookmark manager by picking tiny moves — you never '
          'write code. Tools: act_with_project (sub-actions: list, add, '
          'link, set_prop, materialize, run), intent_define, intent_call.\n'
          'Every move answers with just what changed (point zoom). Use '
          'action list with zoom: point/local/region/summary to see the '
          'project at different sizes; summary = whole picture, no details.\n'
          'Steps: 1) intent_define two intents: save_url with param '
          '"url:string" returning "bool", and list_saved returning "int". '
          '2) act_with_project: add op nodes (kind "op", label is the op '
          'name, id auto-assigned op_1, op_2, ... in add order) from this '
          'closed vocabulary: load_arg, load_state, push_state, literal, '
          'list_len, starts_with, eq, not, jump_if_false, return. Each op '
          'takes props a (argument, e.g. "url") and/or b (value, e.g. '
          '"http" or a JSON literal like \'{"saved": true}\'). 3) link '
          '"impl" from each intent name to its FIRST op (save_url->op_1, '
          'list_saved->its first op), then link "then" from each op to the '
          'next op in its chain. jump_if_false takes prop b = the target op '
          'id it jumps to when the top value is false. 4) materialize. '
          '5) verify yourself: intent_call save_url with args '
          '["url=https://check.dev"], then intent_call list_saved. The '
          'result comes back as a tool result.',
    ),
    ActorThreads(threads: []),
    ActorTools(registryName: 'default'),
    PresentInScene(sceneEntity: scene),
    OpenDecision(
      prompt:
          'Build a bookmark manager: define save_url (saves a URL only if it '
          'starts with http) and list_saved (counts saved bookmarks), shape '
          'their executor logic through meaning moves, materialize, and '
          'verify by calling the intents.',
    ),
  ]);
  final thread = spawnThread(world, actor, scene);
  world.upsertComponent(actor, ActorThreads(threads: [thread]));
  world.flush();

  // Verifier-in-the-loop (same mechanical pattern as the coding suite):
  // run → intent-graded oracle → on failure feed the failure back as a new
  // OpenDecision (NO LLM in the retry loop itself — each retry is an honest
  // generation). Bounded by maxRetries. Premature-completion and drift are
  // recovered mechanically; a model that can't recover is an honest FAIL.
  const maxRetries = 3;
  const oraclePrompt =
      'Build a bookmark manager: define save_url (saves a URL only if it '
      'starts with http) and list_saved (counts saved bookmarks), shape '
      'their executor logic through meaning moves, materialize, and '
      'verify by calling the intents.';
  var oracle = _notRun; // never-run sentinel; replaced on first oracle pass
  var retries = 0;
  while (true) {
    await HarnessLoop(world: world).runUntilIdle();
    File('${jail.path}/intent_calls.json').writeAsStringSync(_oracleCalls);
    File(
      '${jail.path}/intent_runner.dart',
    ).writeAsStringSync(_intentRunnerSource);
    final program = File('${jail.path}/program.dart');
    oracle = program.existsSync()
        ? await Process.run(
            'dart', ['run', 'intent_runner.dart'],
            workingDirectory: jail.path,
          )
        : (ProcessResult(0, -1, '', 'program.dart never materialized'));
    if (oracle.exitCode == 0 || retries >= maxRetries) break;
    retries++;
    world.upsertComponent(
      actor,
      OpenDecision(
        prompt: 'Your previous attempt did not satisfy the intent '
            'verification. Failing check: intents checker — '
            '${(oracle.stdout as String).trim()}\n\n'
            'Fix the meaning tree (check your op chains with action list — '
            'every intent needs an impl edge to a FIRST op and a then-chain '
            'to a return op; if an op is missing props a or b, fix it with '
            'set_prop using the op id from the error), re-materialize, and '
            'call the intents to verify. Original task:\n$oraclePrompt',
      ),
    );
    world.flush();
  }

  final view = meaningView(world);
  // Moves from the durable thread record: every internal tool round is a
  // beat — the response object only carries the final round's calls.
  final moves = <String, int>{};
  final beatIndex = world.getResource<FacetIndex>();
  for (final beat in beatIndex.beatsOfThread(thread).toList()) {
    final we = world.getEntity(beat).$1;
    final call = we.get<BeatToolCall>();
    if (call == null) continue;
    final action = call.args['action'];
    moves.update(
      action is String ? '${call.name}.$action' : call.name,
      (v) => v + 1,
      ifAbsent: () => 1,
    );
  }
  stdout
    ..writeln('intent_closure (AFM):')
    ..writeln('  decisions: ${meter.decisions}')
    ..writeln('  tool rounds (from thread beats): '
        '${moves.values.fold(0, (a, b) => a + b)}')
    ..writeln('  moves: ${moves}')
    ..writeln('  projection tokens (honest spend): ${meter.projectionTokens}')
    ..writeln('  nodes: ${view.nodeCount}, edges: ${view.edgeCount}')
    ..writeln('  program.dart exists: ${File('${jail.path}/program.dart').existsSync()}')
    ..writeln('  oracle exit: ${oracle.exitCode} (retries: $retries)')
    ..writeln('  oracle stdout: ${(oracle.stdout as String).trim()}');
  exit(oracle.exitCode == 0 ? 0 : 1);
}
