// Regenerates lib/src/owned_session_launch_embed.dart from owned_session_p1_leader.pl.
//
//   dart run tool/embed_owned_session_leader.dart

import 'dart:io';

void main() {
  final packageRoot = Directory.current;
  if (!File('${packageRoot.path}/pubspec.yaml').existsSync()) {
    stderr.writeln('run from pkgs/xsoulspace_tooling_runtime');
    exit(1);
  }
  final pl = File('tool/owned_session_p1_leader.pl').readAsStringSync();
  final lines = pl.split('\n');
  var start = 0;
  if (lines.first.startsWith('#!')) start = 1;
  while (start < lines.length &&
      (lines[start].trim().isEmpty || lines[start].trim().startsWith('#'))) {
    start++;
  }
  final body = lines
      .sublist(start)
      .where((line) {
        final trimmed = line.trim();
        return trimmed != 'use strict;' && trimmed != 'use warnings;';
      })
      .join('\n');
  final out = File('lib/src/owned_session_launch_embed.dart');
  out.writeAsStringSync('''
// GENERATED by tool/embed_owned_session_leader.dart — do not edit by hand.

/// Perl body passed to `perl -MPOSIX -e` for owned-session launches.
const ownedSessionLaunchEmbed = r\'\'\'
$body\'\'\';
''');
  stdout.writeln('wrote ${out.path} (${body.length} bytes)');
}
